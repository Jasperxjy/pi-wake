#!/usr/bin/env node
/**
 * Live-iteration bridge: writes a gitignored dev shim into .pi/extensions/ so
 * pi sessions opened in this repo auto-discover the pi-wake extension FROM
 * SOURCE. Combine with /reload (hot-reload for auto-discovered extensions):
 *
 *   npm run dev:link   # once (or after removing it)
 *   <open pi here>     # widget/status render from the repo source
 *   <edit *.ts>        # iterate...
 *   /reload            # re-imports the extension - no new session needed
 *
 * The shim is deliberately NOT committed: shipping it would double-load the
 * extension for everyone else (tool-name conflict) and pin their sessions to
 * this checkout. Remove with `npm run dev:unlink`.
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = path.resolve(process.cwd());
const shimDir = path.join(repoRoot, ".pi", "extensions");
const shimPath = path.join(shimDir, "pi-wake.dev.ts");

if (process.argv.includes("--unlink")) {
	await rm(shimPath, { force: true });
	console.log(`dev:link removed (${path.relative(repoRoot, shimPath)})`);
	process.exit(0);
}

const isRepo = await readFile(path.join(repoRoot, "package.json")).then((text) => JSON.parse(text).name === "pi-wake").catch(() => false);
if (!isRepo) throw new Error("run this from the pi-wake repo root");
// Auto-discovery loads BOTH the shim and any user-level pi-wake install; two
// wake_alarm registrations abort pi at startup ("Tool wake_alarm conflicts").
// Detect the collision up front so the dev loop starts clean.
const { homedir } = await import("node:os");
const userInstall = path.join(homedir(), ".pi", "agent", "npm", "node_modules", "pi-wake");
const userInstalled = await readFile(path.join(userInstall, "package.json")).then((text) => JSON.parse(text).name === "pi-wake").catch(() => false);
if (userInstalled) {
	console.error(`CONFLICT: a user-level pi-wake is installed at ${userInstall}.`);
	console.error("Auto-discovery would load BOTH it and this dev shim, and pi aborts on the duplicate wake_alarm tool.");
	console.error("While developing locally, remove it:  pi remove npm:pi-wake");
	console.error("(reinstall any time with:            pi install npm:pi-wake)");
	process.exit(1);
}
await mkdir(shimDir, { recursive: true });
await writeFile(shimPath, `// Generated by npm run dev:link - gitignored on purpose, do not commit.
// Re-exports the repo-source extension so /reload picks up edits live.
import piWake from "../../extensions/pi-wake/index.ts";
export default piWake;
`);
console.log(`dev shim written: ${path.relative(repoRoot, shimPath)}`);
console.log("open pi in this repo, then /reload after edits; remove with npm run dev:unlink");

